"""
The release lock's machinery (scripts/lock.py, `make lock`, `make lock-check`,
bootstrap.sh's locked branch), with stand-ins.

No lock here is a resolve. Every lock file in this module is built from
pyproject.toml's own requirements at the versions their specifiers name, with
digests that are the right shape and of nothing, because the property under
test is what lock-check and bootstrap do with a file of that shape, and the
machine this runs on reaches no index. `make lock` is run against a uv stand-in
that writes such a file where uv would.
"""

