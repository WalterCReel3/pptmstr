def test_the_runtime_lock_is_the_dev_locks_versions_and_hashes() -> None:
    entries, _ = lock.parse_lock(GOOD_RUNTIME, "x")
    fonttools = next(e for e in entries if e.name == "fonttools")
    other_version = swap(GOOD_RUNTIME, f"fonttools=={fonttools.version}", "fonttools==9.9")
    assert "fonttools is 9.9 in requirements.lock and 4.50 in requirements-dev.lock" in problems(
        runtime=other_version
    )
    other_hash = swap(GOOD_RUNTIME, fonttools.hashes[0], digest("another file"))
    assert "fonttools has different hashes in requirements.lock and requirements-dev.lock" in (
        problems(runtime=other_hash)
    )
    extra = GOOD_RUNTIME + entry_line("six", "1.0", None, [digest("six")])
    assert "requirements.lock has six, which requirements-dev.lock does not" in problems(extra)


