def test_imtypeset_locked_for_linux_only_leaves_the_mac_uncovered() -> None:
    """
    A marker on the locked entry that is narrower than pyproject's requirement.
    """
    narrow = "sys_platform == 'linux'"
    runtime_entries, _ = lock.parse_lock(GOOD_RUNTIME, "x")
    imtypeset = next(e for e in runtime_entries if e.name == "imtypeset")
    old = imtypeset.line
    new = f"imtypeset=={imtypeset.version} ; {narrow}"
    said = problems(swap(GOOD_RUNTIME, old, new), swap(GOOD_DEV, old, new))
    for python in lock.TARGET_PYTHONS:
        assert (
            f"requirements.lock has no imtypeset for darwin arm64 CPython {python}, "
            f"where pyproject.toml requires it"
        ) in said
    assert not any("linux x86_64" in p for p in said)


