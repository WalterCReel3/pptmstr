def _facts(system: str, machine: str, python: tuple[int, int]) -> object:
    return probe.PlatformFacts(
        system=system,
        machine=machine,
        implementation="CPython",
        python=python,
        macos=(14, 0) if system == "darwin" else None,
        glibc=(2, 28) if system == "linux" else None,
    )


GRID = [
    (system, machine, (3, minor))
    for system, machine in (
        ("linux", "x86_64"),
        ("linux", "aarch64"),
        ("darwin", "arm64"),
        ("darwin", "x86_64"),
    )
    for minor in (10, 11, 12, 13, 14, 15)
]


def _env(system: str, machine: str, python: tuple[int, int]) -> dict[str, str]:
    version = f"{python[0]}.{python[1]}"
    return {
        "sys_platform": system,
        "platform_machine": machine,
        "platform_system": "Linux" if system == "linux" else "Darwin",
        "python_version": version,
        "python_full_version": f"{version}.0",
        "implementation_name": "cpython",
        "platform_python_implementation": "CPython",
        "os_name": "posix",
        "platform_release": "",
        "platform_version": "",
        "implementation_version": f"{version}.0",
    }


@pytest.mark.parametrize("system, machine, python", GRID)
def test_pyprojects_environments_the_probe_and_lock_py_name_the_same_targets(
    system: str, machine: str, python: tuple[int, int]
) -> None:
    """
    [tool.uv].environments (what uv resolves for), the probe's LIBRARY verdict
    (what bootstrap lets the lock install on) and lock.TARGET_* (what lock-check
    holds the lock to) agree at every point of the grid. Where a marker cannot
    see (glibc, the macOS version) the probe is given the floor.
    """
    env = _env(system, machine, python)
    in_pyproject = any(Marker(m).evaluate(env) for m in PYPROJECT["tool"]["uv"]["environments"])
    in_probe = probe.install_outlook(_facts(system, machine, python)).verdict == probe.LIBRARY
    in_lock_py = any(
        all(env[k] == v for k, v in target.items() if k in env)
        for target in lock.target_environments()
    )
    assert in_pyproject == in_probe == in_lock_py


