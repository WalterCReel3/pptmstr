def test_a_lock_in_uvs_shape_is_read_with_its_markers_and_hashes() -> None:
    text = (
        "# header\n"
        "colorama==0.4.6 ; sys_platform == 'win32' \\\n"
        f"    --hash={digest('c', '1')} \\\n"
        f"    --hash={digest('c', '2')}\n"
        "    # via\n"
        "    #   click\n"
        "    #   pytest\n"
        "\n"
        f"Typing_Extensions==4.12.2 --hash={digest('t')}\n"
    )
    entries, said = lock.parse_lock(text, "the lock")
    assert said == []
    assert [(e.name, e.version, e.marker) for e in entries] == [
        ("colorama", "0.4.6", 'sys_platform == "win32"'),
        ("typing-extensions", "4.12.2", None),
    ]
    assert entries[0].hashes == (digest("c", "1"), digest("c", "2"))


