# --- bootstrap.sh's two branches, with stand-ins -----------------------------------
#
# Never this worktree's own bootstrap: it would install into its .venv. A copy runs
# with an interpreter, a venv interpreter and a uv that only record what they were
# asked, as tests/test_probe.py's do.

PYTHON_STAND_IN = """#!/bin/sh
echo "python $*" >> "$STANDIN_LOG"
case "$1" in
  -c) exit 0 ;;
  scripts/probe.py) echo "probe stand-in"; exit 0 ;;
  scripts/lock.py)
    if [ "$2" = covers ]; then
      [ "$STANDIN_COVERS" = 1 ] && { echo "    the release lock covers stand-in"; exit 1; }
      exit 0
    fi
    if [ "$2" = subset ]; then
      echo "imscribe==0.2.0 --hash=sha256:aa"
      exit 0
    fi ;;
  -m) if [ "$2" = venv ]; then
        mkdir -p .venv/bin
        cp "$STANDIN_VENV_PYTHON" .venv/bin/python
      fi
      exit 0 ;;
esac
exit 0
"""

VENV_PYTHON_STAND_IN = """#!/bin/sh
echo "venv-python $*" >> "$STANDIN_LOG"
if [ "$1" = -m ] && [ "$2" = pptmstr.pairing ] && [ "$3" = unpublished ]; then
  echo "$STANDIN_REPLACE"
fi
exit 0
"""

BOOT_UV_STAND_IN = """#!/bin/sh
echo "uv $*" >> "$STANDIN_LOG"
if [ "$1" = venv ]; then
  mkdir -p .venv/bin
  [ -e .venv/bin/python ] || cp "$STANDIN_VENV_PYTHON" .venv/bin/python
fi
exit 0
"""


def _stand_in(path: Path, text: str) -> Path:
    path.write_text(text, encoding="utf-8")
    path.chmod(0o755)
    return path


def _bootstrap(
    tmp_path: Path,
    *,
    uv: bool,
    locked: bool,
    args: tuple[str, ...] = (),
    covers: bool = True,
    replace: str = "",
    environ: dict[str, str] | None = None,
) -> tuple[subprocess.CompletedProcess, list[str], Path]:
    work = tmp_path / "checkout"
    (work / "scripts").mkdir(parents=True)
    shutil.copy2(ROOT / "bootstrap.sh", work / "bootstrap.sh")
    if locked:
        (work / lock.DEV_LOCK).write_text(GOOD_DEV, encoding="utf-8")
    stubs = tmp_path / "bin"
    stubs.mkdir()
    python = _stand_in(stubs / "python-stand-in", PYTHON_STAND_IN)
    venv_python = _stand_in(tmp_path / "venv-python", VENV_PYTHON_STAND_IN)
    if uv:
        _stand_in(stubs / "uv", BOOT_UV_STAND_IN)
    log = tmp_path / "log"
    log.write_text("", encoding="utf-8")
    system = os.pathsep.join(p for p in ("/usr/bin", "/bin") if Path(p).is_dir())
    env = {
        "PATH": f"{stubs}{os.pathsep}{system}",
        "HOME": str(tmp_path),
        "STANDIN_LOG": str(log),
        "STANDIN_VENV_PYTHON": str(venv_python),
        "STANDIN_REPLACE": replace,
        "STANDIN_COVERS": "0" if covers else "1",
        **(environ or {}),
    }
    done = subprocess.run(
        ["bash", str(work / "bootstrap.sh"), "--no-window", *args, "--python", str(python)],
        capture_output=True,
        text=True,
        env=env,
        cwd=tmp_path,
        timeout=120,
    )
    return done, log.read_text(encoding="utf-8").splitlines(), work


needs_bash = pytest.mark.skipif(shutil.which("bash") is None, reason="bash is not installed")
BOTH = pytest.mark.parametrize("uv", [pytest.param(True, id="uv"), pytest.param(False, id="pip")])


def _no_system_uv(uv: bool) -> None:
    if not uv and shutil.which("uv", path="/usr/bin:/bin"):
        pytest.skip("a uv in /usr/bin or /bin would be taken where the pip branch is under test")


def _installs(log: list[str]) -> list[str]:
    return [line for line in log if " install " in line]


@needs_bash
@BOTH
def test_with_a_lock_bootstrap_installs_exactly_it_and_then_pptmstr_alone(
    tmp_path: Path, uv: bool
) -> None:
    _no_system_uv(uv)
    done, log, _ = _bootstrap(tmp_path, uv=uv, locked=True)
    assert done.returncode == 0, done.stdout + done.stderr
    assert "locked: installing exactly what requirements-dev.lock names" in done.stdout
    assert "UNLOCKED" not in done.stdout
    prefix = "uv pip install --python .venv/bin/python" if uv else "venv-python -m pip install"
    # No pip from the index ahead of the hashed install, and no other install.
    assert _installs(log) == [
        f"{prefix} --require-hashes --only-binary :all: -r requirements-dev.lock",
        f"{prefix} --no-deps --no-build-isolation -e .",
    ]
    covers = next(n for n, line in enumerate(log) if "scripts/lock.py covers" in line)
    first_install = next(n for n, line in enumerate(log) if " install " in line)
    assert covers < first_install


@needs_bash
@BOTH
def test_without_a_lock_bootstrap_installs_the_floors_and_says_it_is_unlocked(
    tmp_path: Path, uv: bool
) -> None:
    _no_system_uv(uv)
    done, log, _ = _bootstrap(tmp_path, uv=uv, locked=False)
