ROOT = Path(__file__).resolve().parent.parent


def _load(name: str) -> ModuleType:
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, ROOT / "scripts" / f"{name}.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


probe = _load("probe")
lock = _load("lock")

with (ROOT / "pyproject.toml").open("rb") as _f:
    PYPROJECT = tomllib.load(_f)


# --- stand-in locks --------------------------------------------------------------


def digest(*parts: str) -> str:
    return "sha256:" + hashlib.sha256("|".join(parts).encode()).hexdigest()


def version_for(req: Requirement) -> str:
    for spec in req.specifier:
        if spec.operator in ("==", ">="):
            return spec.version
    return "1.0"


def entry_line(name: str, version: str, marker: str | None, hashes: list[str]) -> str:
    head = f"{name}=={version}" + (f" ; {marker}" if marker else "")
    lines = [head + " \\"]
    for n, h in enumerate(hashes):
        lines.append(f"    --hash={h}" + (" \\" if n < len(hashes) - 1 else ""))
    lines.append("    # via pptmstr (pyproject.toml)")
    return "\n".join(lines) + "\n"


def stand_in_lock(requirements: list[str], *, header: bool = True) -> str:
    """
    A lock in uv's requirements shape with an entry for each of `requirements`.
    """
    out = []
    if header:
        out.append(
            "# This file was autogenerated by uv via the following command:\n#    make lock\n"
        )
    seen = set()
    for text in requirements:
        req = Requirement(text)
        name = lock.canonical(req.name)
        if name in seen:
            continue
        seen.add(name)
        version = version_for(req)
        marker = str(req.marker) if req.marker else None
        out.append(
            entry_line(name, version, marker, [digest(name, version, "a"), digest(name, version)])
        )
    return "".join(out)


RUNTIME, DEV, BUILD = lock.requirements_of(PYPROJECT)
GOOD_RUNTIME = stand_in_lock(RUNTIME)
GOOD_DEV = stand_in_lock(RUNTIME + DEV + BUILD)


def problems(runtime: str = GOOD_RUNTIME, dev: str = GOOD_DEV) -> list[str]:
    return list(lock.check_locks(PYPROJECT, runtime, dev))


def swap(text: str, old: str, new: str) -> str:
    assert text.count(old) >= 1, old
    return text.replace(old, new)


